"""Summarise the experiment matrix into one Markdown table (experiments/results/MATRIX.md).

For every (model, task, seed) job it reports, per regime: status per cycle, first alarm,
accuracy at baseline / at the first alarm / at the end, audit accuracy (questions the guard
never saw), and guard rejections. Then it checks the claims the README makes:

* control quiet: the faithful regime raised no alarm;
* bad regimes caught: every unguarded recursive regime alarmed;
* early warning: accuracy lost by the time of the first alarm vs. lost by the end;
* guard protects: the guarded regime's end accuracy vs. the unguarded one, on the audit suite.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

MARK = {"OK": "·", "WATCH": "~", "ALARM": "▲"}


def fmt(x) -> str:
    return "–" if x is None else f"{x:.2f}"


def main(root: str = "experiments/results/matrix", out: str = "experiments/results/MATRIX.md") -> int:
    jobs = sorted(p for p in Path(root).iterdir() if (p / "summary.json").is_file()) if Path(root).is_dir() else []
    if not jobs:
        print("no finished jobs", file=sys.stderr)
        return 1
    lines = ["# REGRESS on real models: experiment matrix", "",
             "Generated by `experiments/aggregate.py` from `experiments/results/matrix/*/summary.json`.",
             "Status per cycle: · ok, ~ watch, ▲ alarm. *Audit* = questions held out from the gate.", "",
             "| job | regime | status | first alarm | acc base → alarm → end | audit base → end | guard rejected |",
             "|---|---|---|---|---|---|---|"]
    checks = []
    for job in jobs:
        s = json.loads((job / "summary.json").read_text())
        res = s["results"]
        for name, r in res.items():
            acc = r["accuracy"]
            fa = r["first_alarm"]
            at_alarm = acc[fa] if fa is not None and fa < len(acc) else None
            audit = r.get("audit_accuracy") or []
            g = r.get("guard")
            lines.append(
                f"| {job.name} | {name} | {''.join(MARK.get(x, '?') for x in r['statuses'])} | {fa} | "
                f"{fmt(acc[0])} → {fmt(at_alarm)} → {fmt(acc[-1])} | "
                f"{fmt(audit[0] if audit else None)} → {fmt(audit[-1] if audit else None)} | "
                f"{(str(g['rejected']) + '/' + str(g['decisions'])) if g else '–'} |")
        ctrl = res.get("faithful")
        full, gf = res.get("full"), res.get("full+guard")
        grad = res.get("gradual")
        row = {"job": job.name,
               "control_quiet": ctrl is not None and ctrl["first_alarm"] is None,
               "full_caught": full is not None and full["first_alarm"] is not None,
               "gradual_caught": grad is not None and grad["first_alarm"] is not None}
        if grad and grad["first_alarm"] is not None:
            a = grad["accuracy"]
            row["gradual_lost_at_alarm"] = a[0] - a[grad["first_alarm"]]
            row["gradual_lost_by_end"] = a[0] - a[-1]
        if full and gf:
            row["guard_end_acc"], row["unguarded_end_acc"] = gf["accuracy"][-1], full["accuracy"][-1]
            if gf.get("audit_accuracy") and full.get("audit_accuracy"):
                row["guard_end_audit"], row["unguarded_end_audit"] = gf["audit_accuracy"][-1], full["audit_accuracy"][-1]
        checks.append(row)
    lines += ["", "## Claims checked per job", "",
              "| job | control quiet | full caught | gradual caught | gradual: lost at alarm / by end | "
              "guard end acc (audit) vs unguarded (audit) |", "|---|---|---|---|---|---|"]
    for c in checks:
        ga = (f"{fmt(c.get('guard_end_acc'))} ({fmt(c.get('guard_end_audit'))}) vs "
              f"{fmt(c.get('unguarded_end_acc'))} ({fmt(c.get('unguarded_end_audit'))})") if "guard_end_acc" in c else "–"
        lost = (f"{fmt(c.get('gradual_lost_at_alarm'))} / {fmt(c.get('gradual_lost_by_end'))}"
                if "gradual_lost_at_alarm" in c else "–")
        lines.append(f"| {c['job']} | {'yes' if c['control_quiet'] else '**no**'} | "
                     f"{'yes' if c['full_caught'] else '**no**'} | {'yes' if c['gradual_caught'] else '**no**'} | "
                     f"{lost} | {ga} |")
    Path(out).write_text("\n".join(lines) + "\n")
    Path(out).with_suffix(".json").write_text(json.dumps(checks, indent=1))
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:]))
